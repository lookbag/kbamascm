-- ============================================================
-- 1. VENDORS
-- ============================================================
CREATE TABLE vendors (
    vendor_code         TEXT PRIMARY KEY,
    vendor_name         TEXT NOT NULL,
    country             TEXT,
    address_line1       TEXT,
    address_line2       TEXT,
    city                TEXT,
    state_province      TEXT,
    postal_code         TEXT,
    country_full        TEXT,
    contact_name        TEXT,
    email               TEXT,
    phone               TEXT,
    fax                 TEXT,
    default_currency    TEXT DEFAULT 'USD',
    payment_terms       TEXT,
    incoterms           TEXT,
    bank_name           TEXT,
    bank_account        TEXT,
    swift_code          TEXT,
    iban                TEXT,
    remarks             TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    updated_at          TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================
-- 2. PARTS
-- ============================================================
CREATE TABLE parts (
    part_no             TEXT PRIMARY KEY,
    part_name           TEXT NOT NULL,
    category            TEXT,
    in_out              TEXT CHECK (in_out IN ('in','out','')),
    material            TEXT,
    vendor_code         TEXT REFERENCES vendors(vendor_code),
    price               NUMERIC DEFAULT 0,
    currency            TEXT DEFAULT 'KRW',
    price_date          DATE,
    moq                 INTEGER DEFAULT 0,
    std_pack_size       INTEGER DEFAULT 0,
    leadtime_mp         INTEGER DEFAULT 0,
    leadtime_dev        INTEGER DEFAULT 0,
    incoterms           TEXT,
    shipping_method     TEXT,
    safety_stock        TEXT,
    hs_code             TEXT,
    unit                TEXT DEFAULT 'Pcs',
    remarks             TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    updated_at          TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================
-- 3. PRODUCTS
-- ============================================================
CREATE TABLE products (
    part_no             TEXT PRIMARY KEY,
    kb_part_no          TEXT,
    car_code            TEXT,
    sub_code            TEXT,
    part_name           TEXT NOT NULL,
    customer            TEXT,
    type                TEXT DEFAULT 'mp' CHECK (type IN ('mp','dev')),
    price               NUMERIC DEFAULT 0,
    currency            TEXT DEFAULT 'USD',
    incoterms           TEXT,
    remarks             TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    updated_at          TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================
-- 4. BOM
-- ============================================================
CREATE TABLE bom (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assy_part_no        TEXT NOT NULL REFERENCES products(part_no),
    part_no             TEXT NOT NULL REFERENCES parts(part_no),
    lr                  TEXT DEFAULT '-' CHECK (lr IN ('L','R','-')),
    qty                 NUMERIC NOT NULL DEFAULT 1,
    car_code            TEXT,
    sub_code            TEXT,
    remarks             TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (assy_part_no, part_no, lr)
);

-- ============================================================
-- 5. INVENTORY
-- ============================================================
CREATE TABLE inventory (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_no             TEXT NOT NULL REFERENCES parts(part_no),
    location            TEXT NOT NULL CHECK (location IN ('onhand','intransit','vmi')),
    qty                 NUMERIC DEFAULT 0,
    warehouse           TEXT,
    eta                 DATE,
    po_no               TEXT,
    remarks             TEXT,
    last_updated        TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (part_no, location, po_no)
);

-- ============================================================
-- 6. FORECAST
-- ============================================================
CREATE TABLE forecast (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assy_part_no        TEXT NOT NULL REFERENCES products(part_no),
    customer            TEXT,
    year                INTEGER NOT NULL,
    week                INTEGER NOT NULL,
    week_key            TEXT NOT NULL,
    week_start_date     DATE,
    qty                 NUMERIC NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    updated_at          TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (assy_part_no, year, week)
);

-- ============================================================
-- 7. PO HEADERS
-- ============================================================
CREATE TABLE po_headers (
    po_no               TEXT PRIMARY KEY,
    vendor_code         TEXT REFERENCES vendors(vendor_code),
    po_date             DATE NOT NULL DEFAULT CURRENT_DATE,
    currency            TEXT DEFAULT 'USD',
    incoterms           TEXT,
    payment_terms       TEXT,
    ship_to             TEXT,
    remarks             TEXT,
    status              TEXT DEFAULT 'draft' CHECK (status IN ('draft','issued','confirmed','partial','received','closed','cancelled')),
    created_by          TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    updated_at          TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================
-- 8. PO LINES
-- ============================================================
CREATE TABLE po_lines (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_no               TEXT NOT NULL REFERENCES po_headers(po_no),
    line_no             INTEGER NOT NULL DEFAULT 1,
    part_no             TEXT NOT NULL REFERENCES parts(part_no),
    qty_ordered         NUMERIC NOT NULL DEFAULT 0,
    qty_received        NUMERIC DEFAULT 0,
    unit_price          NUMERIC DEFAULT 0,
    currency            TEXT,
    amount              NUMERIC GENERATED ALWAYS AS (qty_ordered * unit_price) STORED,
    required_date       DATE,
    eta                 DATE,
    remarks             TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (po_no, line_no)
);

-- ============================================================
