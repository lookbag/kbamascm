-- ============================================================
-- UPDATED_AT 자동 갱신 트리거
-- ============================================================
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER vendors_updated_at     BEFORE UPDATE ON vendors     FOR EACH ROW EXECUTE FUNCTION update_updated_at();
CREATE TRIGGER parts_updated_at       BEFORE UPDATE ON parts       FOR EACH ROW EXECUTE FUNCTION update_updated_at();
CREATE TRIGGER products_updated_at    BEFORE UPDATE ON products    FOR EACH ROW EXECUTE FUNCTION update_updated_at();
CREATE TRIGGER forecast_updated_at    BEFORE UPDATE ON forecast    FOR EACH ROW EXECUTE FUNCTION update_updated_at();
CREATE TRIGGER po_updated_at          BEFORE UPDATE ON po_headers  FOR EACH ROW EXECUTE FUNCTION update_updated_at();
CREATE TRIGGER salesorders_updated_at BEFORE UPDATE ON salesorders FOR EACH ROW EXECUTE FUNCTION update_updated_at();
CREATE TRIGGER workorders_updated_at  BEFORE UPDATE ON workorders  FOR EACH ROW EXECUTE FUNCTION update_updated_at();

