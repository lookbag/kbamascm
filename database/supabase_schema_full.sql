CREATE OR REPLACE VIEW v_parts_with_vendor AS
SELECT p.*, v.vendor_name, v.country AS vendor_country,
       v.contact_name AS vendor_contact, v.email AS vendor_email
FROM parts p LEFT JOIN vendors v ON p.vendor_code = v.vendor_code;

CREATE OR REPLACE VIEW v_bom_detail AS
SELECT b.id, b.assy_part_no, pr.part_name AS assy_name, pr.customer,
       b.part_no, pt.part_name, pt.vendor_code, v.vendor_name,
       b.lr, b.qty, pt.leadtime_mp, pt.moq, pt.price, pt.currency
FROM bom b
JOIN products pr ON b.assy_part_no = pr.part_no
JOIN parts    pt ON b.part_no      = pt.part_no
LEFT JOIN vendors v ON pt.vendor_code = v.vendor_code;

CREATE OR REPLACE VIEW v_inventory_summary AS
SELECT i.part_no, p.part_name, p.vendor_code, p.leadtime_mp, p.moq, p.safety_stock,
       SUM(CASE WHEN i.location = 'onhand'    THEN i.qty ELSE 0 END) AS qty_onhand,
       SUM(CASE WHEN i.location = 'intransit' THEN i.qty ELSE 0 END) AS qty_intransit,
       SUM(CASE WHEN i.location = 'vmi'       THEN i.qty ELSE 0 END) AS qty_vmi,
       SUM(i.qty) AS qty_total,
       MAX(CASE WHEN i.location = 'intransit' THEN i.eta END) AS next_eta
FROM inventory i JOIN parts p ON i.part_no = p.part_no
GROUP BY i.part_no, p.part_name, p.vendor_code, p.leadtime_mp, p.moq, p.safety_stock;

CREATE OR REPLACE VIEW v_forecast_weekly AS
SELECT f.year, f.week, f.week_key, f.week_start_date,
       f.assy_part_no, pr.part_name AS assy_name, f.customer, f.qty
FROM forecast f JOIN products pr ON f.assy_part_no = pr.part_no
ORDER BY f.year, f.week, f.assy_part_no;

